CREATE TABLE CLIENT(
	DOC_NUMBER NVARCHAR(20) NOT NULL PRIMARY KEY,
	CLIENT_NAME NVARCHAR(250) NOT NULL,
	CELLPHONE NVARCHAR(100) NULL,
	EMAIL NVARCHAR(200) NULL,
	CREATION_DATE  DATETIME2 DEFAULT GETDATE(),
